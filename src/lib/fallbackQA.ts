export function findFallback(message: string): string {
  const m = message.toLowerCase().trim();
  if (!m) return "میٚ سمجھ نہیں پایا، ذرا دوبارہ پوچھیں";
  for (const { q, a } of FALLBACK_QA) {
    const qLower = q.toLowerCase();
    if (m.includes(qLower) || qLower.includes(m)) return a;
  }
  return "میٚ سمجھ نہیں پایا، ذرا دوبارہ پوچھیں";
}
